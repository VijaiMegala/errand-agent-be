import { createHash } from 'node:crypto';
import { readFile, writeFile } from 'node:fs/promises';
import '../config.js';

const key = process.env.LANGSMITH_API_KEY?.trim();
if (!key) throw new Error('LANGSMITH_API_KEY is required for eval upload');
const { startedAt, completedAt, results } = JSON.parse(
  await readFile(new URL('./results/latest.json', import.meta.url), 'utf8'));
if (!Array.isArray(results) || !results.length) throw new Error('Run npm run eval first');

function stableRowId(name) {
  const hex = createHash('sha1').update(`service-booking-agent-v1:${name}`).digest('hex').slice(0, 32);
  return `${hex.slice(0, 8)}-${hex.slice(8, 12)}-5${hex.slice(13, 16)}-a${hex.slice(17, 20)}-${hex.slice(20)}`;
}

const rowTimes = results.map((result) => ({
  start: new Date(result.startedAt).toISOString(),
  end: new Date(Math.max(Date.parse(result.completedAt),
    Date.parse(result.startedAt) + 1)).toISOString(),
}));
const body = {
  experiment_name: `service-booking-agent-${startedAt.replace(/[:.]/g, '-')}`,
  experiment_description: 'Synthetic, scripted-model regression scenarios generated by npm run eval.',
  dataset_name: 'service-booking-agent-offline-v1',
  dataset_description: 'Synthetic booking-agent regression scenarios; no customer data.',
  experiment_start_time: new Date(Date.parse(startedAt) - 1).toISOString(),
  experiment_end_time: new Date(Math.max(Date.parse(completedAt),
    ...rowTimes.map((time) => Date.parse(time.end))) + 1).toISOString(),
  experiment_metadata: { source: 'npm run eval', scripted_model: true },
  summary_experiment_scores: [{ key: 'pass_rate', score: results.filter((r) => r.pass).length / results.length }],
  results: results.map((result, index) => ({
    row_id: stableRowId(result.scenario),
    inputs: { scenario: result.scenario },
    expected_outputs: { result: result.expected },
    actual_outputs: { result: result.actual },
    evaluation_scores: [{ key: 'passed', score: result.pass ? 1 : 0, comment: result.notes || undefined }],
    start_time: rowTimes[index].start,
    end_time: rowTimes[index].end,
    run_name: result.scenario,
    run_metadata: { scripted_model: true, latency_ms: result.latencyMs },
  })),
};
const endpoint = new URL('/api/v1/datasets/upload-experiment',
  process.env.LANGSMITH_ENDPOINT || 'https://api.smith.langchain.com');
const response = await fetch(endpoint, { method: 'POST',
  headers: { 'content-type': 'application/json', 'x-api-key': key },
  body: JSON.stringify(body), signal: AbortSignal.timeout(30_000) });
if (!response.ok) throw new Error(`LangSmith eval upload failed: HTTP ${response.status} ${
  (await response.text()).slice(0, 300)}`);
const uploaded = await response.json();
const record = { uploadedAt: new Date().toISOString(),
  experimentId: uploaded.experiment?.id, datasetId: uploaded.dataset?.id,
  experimentName: body.experiment_name, datasetName: body.dataset_name,
  scenarioCount: results.length };
await writeFile(new URL('./results/langsmith-upload.json', import.meta.url),
  JSON.stringify(record, null, 2) + '\n');
console.log(`Uploaded ${record.scenarioCount} synthetic eval rows to LangSmith: ${record.experimentName}`);
